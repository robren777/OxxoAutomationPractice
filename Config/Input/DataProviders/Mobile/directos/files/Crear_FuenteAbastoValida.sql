

-- Obtiene STORE_ID
SELECT @STORE_ID_SOURCE = STORE_ID_SOURCE
FROM XposCloudSettingQA.dbo.STORE_PLACE 
WHERE @CR_STORE = CR_STORE AND @CR_PLACE = CR_PLACE;

-- Obtiene cantidad máxima de pedidos a realizar por tienda
SELECT @CANTMAXPEDGEN = [VALUE] 
FROM XposCloudSettingQA.dbo.SYSTEM_PARAM 
WHERE CODE = 'CANTMAXPED_GEN';

-- Obtiene cantidad máxima de pedidos a recibir por proveedor-tienda
SELECT @CANTMAXPEDREC = [VALUE] 
FROM XposCloudSettingQA.dbo.SYSTEM_PARAM 
WHERE CODE = 'CANTMAXPED';

-- Obtiene cantidad de pedidos abiertos y/o cerrados del proveedor
USE XposCloudPurchaseToolQA;
SELECT S.CD_NMB_SPR,
       COUNT(*) AS Ordenes
INTO #tmpPO
FROM dbo.TR_PURCHASEORDER H
LEFT JOIN PA_SPR S ON S.PA_SPR_ID = H.PA_SPR_ID
WHERE H.DATE_SUPPLY IS NULL AND (@STORE_ID_SOURCE = H.STORE_PLACE_ID)
GROUP BY S.CD_NMB_SPR;

-- Obtiene cantidad de pedidos cerrados del proveedor
SELECT S.CD_NMB_SPR,
       COUNT(*) AS Ordenes
INTO #tmpPOClosed
FROM dbo.TR_PURCHASEORDER H
LEFT JOIN PA_SPR S ON S.PA_SPR_ID = H.PA_SPR_ID
WHERE H.DATE_CLOSE IS NOT NULL 
AND H.DATE_SUPPLY IS NULL AND (@STORE_ID_SOURCE = H.STORE_PLACE_ID)
GROUP BY S.CD_NMB_SPR;

-- Ordenes recibidas por proveedor-hoy
SELECT S.CD_NMB_SPR,
       COUNT(*) AS totOCs
INTO #tmpPORec
FROM dbo.TR_PURCHASEORDER H
LEFT JOIN PA_SPR S ON S.PA_SPR_ID = H.PA_SPR_ID
WHERE H.DATE_SUPPLY IS NOT NULL 
AND (@STORE_ID_SOURCE = H.STORE_PLACE_ID)
AND CONVERT(VARCHAR(8), H.DATE_SUPPLY, 112) = CONVERT(VARCHAR(8), GETDATE(), 112)
GROUP BY S.CD_NMB_SPR;

CREATE TABLE #FAvalida (
    [SUPPLIER_NUM] VARCHAR(100) NOT NULL, -- Especifica el tamaño a 100
    [SUPPLIER_NAME] VARCHAR(100) NOT NULL, -- Especifica el tamaño a 100
    [STATUS] BIT NOT NULL,
    [Can_Create] BIT NOT NULL, 
    [Can_Receive] BIT NOT NULL
);

INSERT INTO #FAvalida
SELECT CAST(C.CD_NMB_SPR AS VARCHAR(100)) AS SUPPLIER_NUM, -- Aumenté el tamaño a 100
       C.NM_SPR AS SUPPLIER_NAME,
       CAST(CASE WHEN @CANTMAXPEDGEN = 0 THEN 1 ELSE CASE WHEN @CANTMAXPEDGEN > ISNULL(PO.Ordenes, 0) THEN 1 ELSE 0 END END AS BIT) AS STATUS,
       CONVERT(BIT, CASE WHEN ISNULL(POClosed.Ordenes, 0) = 0 THEN 1 ELSE 0 END) AS Can_Create,
       CONVERT(BIT, CASE WHEN ISNULL(PoRec.totOCs, 0) >= CONVERT(INT, @CANTMAXPEDREC) THEN 0 ELSE 1 END) AS Can_Receive
FROM [XposCloudPurchaseToolQA].[dbo].[PA_SPR] C
LEFT JOIN #tmpPO PO ON C.CD_NMB_SPR = PO.CD_NMB_SPR
LEFT JOIN #tmpPOClosed POClosed ON C.CD_NMB_SPR = POClosed.CD_NMB_SPR
LEFT JOIN #tmpPORec POREC ON C.CD_NMB_SPR = POREC.CD_NMB_SPR
LEFT JOIN [XposCloudPurchaseToolQA].[dbo].STORE_PLACE SP ON C.STORE_PLACE_ID = SP.STORE_PLACE_ID
WHERE SP.CR_PLACE = @CR_PLACE
AND SP.CR_STORE = @CR_STORE
AND C.CD_NMB_SPR > 0
ORDER BY C.CD_NMB_SPR;