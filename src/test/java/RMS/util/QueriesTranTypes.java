// queries relacionadas a la matriz de tran types

package RMS.util;

public class QueriesTranTypes {
	
	public static final String ITEM_LOC = "SELECT * "
			+ "FROM item_loc "
			+ "WHERE status = 'A' "
			+ "and ITEM = '%s' "
			+ "and  loc = '%s'";

	public static final String ITEM_LOC_CONSIGNACION = "SELECT IL.ITEM, IL.LOCAL_SHORT_DESC, "
			+ "IL.LOC, ISCL.SUPPLIER " + "FROM XXFC_FEM_CONSIGNACION F, "
			+ "ITEM_LOC IL, ITEM_SUPP_COUNTRY_LOC ISCL WHERE " + "F.ITEM = IL.ITEM AND " + "IL.ITEM = ISCL.ITEM AND "
			+ "F.LOC = IL.LOC AND " + "IL.LOC = ISCL.LOC AND " + "F.SUPPLIER = ISCL.SUPPLIER AND "
			+ "ISCL.SUPPLIER = PRIMARY_SUPP AND " + "IL.STATUS = 'A' AND F.MERCH_TYPE = '%s' AND IL.LOC = %s "
			+ "AND ROWNUM <= 20";

	public static final String STORE_NOT_ITEM = "SELECT STORE, STORE_NAME, STORE_CITY "
			+ "FROM STORE WHERE STORE NOT IN " + "(SELECT LOC FROM ITEM_LOC WHERE ITEM = '%s') AND ROWNUM <= 10";

	public static final String POS_MODS_TRAN_TYPE_93 = "SELECT TRAN_TYPE, ITEM, ITEM_SHORT_DESC "
			+ "FROM POS_MODS WHERE ITEM = %s AND TRAN_TYPE = 93";

	public static final String ITEM_ZONE_PRICE = "SELECT * FROM ITEM_ZONE_PRICE "
			+ "WHERE ZONE_GROUP_ID = %s AND ZONE_ID = %s AND ITEM IN "
			+ "(SELECT ITEM FROM ITEM_LOC WHERE LOC = %s AND STATUS = 'A') AND ITEM = '%s'";

	public static final String ITEM_ZONE_PRICE_MU = "SELECT * FROM ITEM_ZONE_PRICE "
			+ "WHERE ZONE_GROUP_ID = %s AND ZONE_ID = %s AND MULTI_UNITS IS NOT NULL AND ITEM IN "
			+ "(SELECT ITEM FROM ITEM_LOC WHERE LOC = %s AND STATUS = 'A') AND ITEM = '%s'";

	public static final String POS_MODS_ITEM_TRAN_TYPE_11 = "SELECT TRAN_TYPE, ITEM, ITEM_SHORT_DESC "
			+ "FROM POS_MODS " + "WHERE ITEM = %s AND TRAN_TYPE = 11";

	public static final String GEOCODE_TXCDE = "SELECT TAX_JURISDICTION_ID "
			+ "FROM GEOCODE_TXCDE WHERE STATE_GEOCODE_ID = '%s'";

	public static final String ITEM_LOC_PRODUCT_TAX_STORE = "SELECT ITEM, LOC, LOCAL_SHORT_DESC, STATUS "
			+ "FROM ITEM_LOC " + "WHERE STATUS IN ('A', 'I') AND ITEM IN "
			+ "(SELECT ITEM FROM PRODUCT_TAX_CODE WHERE TAX_JURISDICTION_ID = %s) AND LOC = %s " + "AND ROWNUM <= 20";

	public static final String POS_MODS_TRAN_TYPE_1 = "SELECT TRAN_TYPE, ITEM, ITEM_SHORT_DESC, STORE"
			+ " FROM POS_MODS WHERE TRAN_TYPE = 1";

	public static final String TAX_RATES_GEOCODE = "SELECT T.TAX_JURISDICTION_ID, G.COUNTRY_GEOCODE_ID, G.STATE_GEOCODE_ID "
			+ "FROM TAX_RATES T, GEOCODE_TXCDE G "
			+ "WHERE T.TAX_JURISDICTION_ID = G.TAX_JURISDICTION_ID AND T.TAX_JURISDICTION_ID = %s";

	public static final String GEOCODE_STORE = "SELECT STORE, GEOCODE_LEVEL, COUNTRY_GEOCODE_ID, STATE_GEOCODE_ID "
			+ "FROM GEOCODE_STORE " + "WHERE STATE_GEOCODE_ID = '%s' AND STORE = %s";

	public static final String XXFC_POS_MODS_TEMP_TRAN_1 = "SELECT TRAN_TYPE, ITEM, ITEM_SHORT_DESC "
			+ "FROM XXFC.XXFC_POS_MODS_TEMP WHERE TRAN_TYPE = 1";

	public static final String XXFC_POS_MODS_TEMP_TRAN = "SELECT TRAN_TYPE, COUNT(*) "
			+ "FROM XXFC.XXFC_POS_MODS_TEMP GROUP BY TRAN_TYPE";

	public static final String UDA_ITEM_LOC = "SELECT UIL.ITEM, UIL.UDA_ID, UIL.UDA_VALUE, "
			+ "UV.UDA_VALUE_DESC, IL.LOCAL_ITEM_DESC " + "FROM UDA_ITEM_LOV UIL, UDA_VALUES UV, ITEM_LOC IL "
			+ "WHERE UV.UDA_ID = UIL.UDA_ID AND " + "UV.UDA_VALUE = UIL.UDA_VALUE AND " + "UV.UDA_ID = '%s' AND "
			+ "UIL.UDA_VALUE = 1 AND " + "UIL.ITEM = IL.ITEM AND " + "IL.LOC = '%s' AND " + "IL.STATUS = 'A'";

	public static final String STORE_CLOSE_DATE_NOT_ITEM = "SELECT * FROM STORE "
			+ "WHERE STORE_CLOSE_DATE IS NULL AND STORE NOT IN " + "(SELECT LOC FROM ITEM_LOC WHERE ITEM = '%s')";

	public static final String POS_MODS_ITEM_STORE = "SELECT TRAN_TYPE, ITEM, ITEM_SHORT_DESC "
			+ "FROM POS_MODS WHERE ITEM = %s AND STORE = '%s'";

	public static final String POS_MODS_ITEM_STORE_TRAN_TYPE = "SELECT TRAN_TYPE, ITEM, ITEM_SHORT_DESC "
			+ "FROM POS_MODS WHERE ITEM = %s AND STORE = '%s' AND TRAN_TYPE = %s";

	public static final String POS_MODS = "SELECT * " + "FROM POS_MODS WHERE ITEM = %s AND STORE = '%s'";

	public static final String XXFC_XXFC_POS_MODS_TEMP_COL = "SELECT * "
			+ "FROM XXFC.XXFC_POS_MODS_TEMP_COL WHERE ITEM = %s AND STORE = '%s'";

	public static final String ITEM_LOC_ITEM_SUPP_COUNTRY = "SELECT * FROM ITEM_LOC IL, ITEM_SUPP_COUNTRY_LOC ISCL, REPL_ITEM_LOC RIL WHERE "
			+ "IL.ITEM = ISCL.ITEM AND " + "ISCL.ITEM = RIL.ITEM AND " + "IL.LOC = ISCL.LOC AND "
			+ "ISCL.LOC = RIL.LOCATION AND " + "IL.PRIMARY_SUPP = ISCL.SUPPLIER AND "
			+ "ISCL.SUPPLIER = RIL.PRIMARY_REPL_SUPPLIER AND " + "RIL.STOCK_CAT = 'D' AND " + "IL.LOC = %s AND "
			+ "IL.STATUS = 'A' AND " + "IL.ITEM = %s";

	public static final String COST_SUSP_SUP_HEAD_STATUS_A = "SELECT * FROM COST_SUSP_SUP_HEAD "
			+ "WHERE COST_CHANGE = %s AND STATUS = 'A'";

	public static final String COST_SUSP_SUP_HEAD_STATUS_E = "SELECT * FROM COST_SUSP_SUP_HEAD "
			+ "WHERE COST_CHANGE = %s AND STATUS = 'E'";

	public static final String POS_MODS_TRAN_TYPE_90_ITEM_STORE = "SELECT TRAN_TYPE, ITEM, ITEM_SHORT_DESC "
			+ "FROM POS_MODS WHERE ITEM = %s AND STORE = '%s' AND TRAN_TYPE = 90";

}
